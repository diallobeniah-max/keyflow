import { app, BrowserWindow, ipcMain } from 'electron';
import { mkdtemp, mkdir, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
app.on('window-all-closed',e=>e.preventDefault());
(async()=>{
  const dir=await mkdtemp(join(tmpdir(),'keyflow-folder-ui-'));
  app.setPath('userData',join(dir,'profile'));
  const root=join(dir,'contents');await mkdir(root);await mkdir(join(root,'Subfolder'));
  await mkdir(join(dir,'outside'));await symlink(join(dir,'outside'),join(root,'linked-folder'),'junction');
  await writeFile(join(root,'Subfolder','nested.txt'),'nested');await writeFile(join(root,'hello.txt'),'hello');
  const sharp=(await import('sharp')).default;
  await sharp({create:{width:160,height:100,channels:3,background:{r:35,g:100,b:180}}}).png().toFile(join(root,'fixture.png'));
  const timer=setTimeout(()=>{console.error('Folder test timed out');app.exit(1)},30000);
  let manager;
  try {
    await app.whenReady();
    const {QuickPreviewWindowManager}=await import('../dist-electron/quick-preview-window.js');
    manager=new QuickPreviewWindowManager(true);
    ipcMain.handle('quick-preview:folder-open-entry',(event,name)=>manager.ownsSender(event.sender.id)?manager.openFolderEntry(name):false);
    ipcMain.handle('quick-preview:folder-thumbnail',(event,name)=>manager.ownsSender(event.sender.id)?manager.folderEntryThumbnail(name):null);
    ipcMain.handle('quick-preview:folder-back',event=>manager.ownsSender(event.sender.id)?manager.folderBack():false);
    ipcMain.handle('quick-preview:folder-expand',(event,name)=>manager.ownsSender(event.sender.id)?manager.expandFolderEntry(name):null);
    ipcMain.handle('quick-preview:folder-open-expanded',(event,parent,name)=>manager.ownsSender(event.sender.id)?manager.openExpandedFolderEntry(parent,name):false);
    manager.warm();const win=BrowserWindow.getAllWindows()[0];
    win.webContents.setBackgroundThrottling(false);
    win.setPosition(-10000,-10000);win.setFocusable(false);manager.showAndCenter=w=>w.showInactive();
    assert.equal(await manager.openPreview(root),true);
    const waitFor=async text=>{const deadline=Date.now()+8000;while(Date.now()<deadline){if((await win.webContents.executeJavaScript('document.body.innerText')).includes(text))return;await new Promise(r=>setTimeout(r,50));}throw Error(`Missing ${text}`)};
    const waitForFile=async text=>{const deadline=Date.now()+8000;while(Date.now()<deadline){if(await win.webContents.executeJavaScript(`document.querySelector('.qpo-text-content')?.textContent===${JSON.stringify(text)}`))return;await new Promise(r=>setTimeout(r,50));}throw Error(`Missing file content ${text}`)};
    await waitFor('Subfolder');
    await win.webContents.executeJavaScript(`document.querySelector('[aria-label="Grid view"]').click()`);
    const thumbnailDeadline=Date.now()+10000;
    while(Date.now()<thumbnailDeadline && !await win.webContents.executeJavaScript(`!!document.querySelector('.qpo-folder-grid-thumbnail')`)) await new Promise(r=>setTimeout(r,50));
    assert.ok(await win.webContents.executeJavaScript(`!!document.querySelector('.qpo-folder-grid-thumbnail')`),'grid should show a Windows image thumbnail');
    await new Promise(r=>setTimeout(r,500));
    await writeFile(resolve('artifacts/quick-preview-folder-grid-check.png'),(await win.webContents.capturePage()).toPNG());
    await win.webContents.executeJavaScript(`document.querySelector('[aria-label="List view"]').click()`);
    await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.qpo-folder-entry')).find(e=>e.textContent.includes('fixture.png')).click()`);
    await new Promise(r=>setTimeout(r,500));
    await writeFile(resolve('artifacts/quick-preview-folder-list-check.png'),(await win.webContents.capturePage()).toPNG());
    assert.equal(await manager.openFolderEntry('../hello.txt'),false,'traversal must be rejected');
    assert.equal(await manager.openFolderEntry('not-listed.txt'),false,'unlisted names must be rejected');
    assert.equal(await manager.openFolderEntry('linked-folder'),false,'linked folders must not escape the selected directory');
    assert.equal(await manager.openExpandedFolderEntry('Subfolder','nested.txt'),false,'nested item requires an expanded listing');
    assert.ok(await manager.expandFolderEntry('Subfolder'));
    assert.equal(await manager.openExpandedFolderEntry('Subfolder','../hello.txt'),false,'nested traversal must be rejected');
    assert.equal(await manager.openExpandedFolderEntry('Subfolder','not-listed.txt'),false,'unlisted nested items must be rejected');
    assert.equal(await manager.openExpandedFolderEntry('Subfolder','nested.txt'),true);
    await waitForFile('nested');assert.equal(await manager.folderBack(),true);await waitFor('nested.txt');
    assert.equal(await manager.folderBack(),true);await waitFor('Subfolder');
    await win.webContents.executeJavaScript(`document.querySelector('[aria-label="Expandable list view"]').click()`);
    await win.webContents.executeJavaScript(`document.querySelector('[aria-label="Expand Subfolder"]').click()`);
    await waitFor('nested.txt');
    await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.qpo-folder-nested button')).find(e=>e.textContent.includes('nested.txt')).click()`);
    assert.ok(await win.webContents.executeJavaScript(`document.querySelector('.qpo-folder-detail')?.innerText.includes('nested.txt')`));
    await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.qpo-folder-nested button')).find(e=>e.textContent.includes('nested.txt')).dispatchEvent(new MouseEvent('dblclick',{bubbles:true}))`);
    await waitForFile('nested');assert.equal(await manager.folderBack(),true);await waitFor('nested.txt');
    assert.equal(await manager.folderBack(),true);await waitFor('Subfolder');
    await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.qpo-folder-entry')).find(e=>e.textContent.includes('Subfolder')).dispatchEvent(new MouseEvent('dblclick',{bubbles:true}))`);
    await waitFor('nested.txt');
    await win.webContents.executeJavaScript(`document.querySelector('[aria-label="Back to folder"]').click()`);
    await waitFor('hello.txt');
    assert.equal(await manager.openFolderEntry('hello.txt'),true);
    await waitFor('hello');
    assert.equal(await manager.folderBack(),true);await waitFor('Subfolder');
    console.log('PASS: folder listing, scoped navigation, file preview, and back');
    clearTimeout(timer);manager.destroy();await rm(dir,{recursive:true,force:true}).catch(()=>{});app.exit(0);
  } catch(e) {console.error(e);clearTimeout(timer);manager?.destroy();await rm(dir,{recursive:true,force:true}).catch(()=>{});app.exit(1)}
})().catch(e=>{console.error(e);app.exit(1)});
